"""Modelica (.mo) 1D system-level thermo-fluid component generator for OpenModelica, Dymola, and Twin Builder."""
from __future__ import annotations
from forge.core.hashes import canonical_json, sha256_hash
from forge.core.models import DuctSpec, PhysicsConditions
from forge.physics.solver_1d import solve_duct_physics


def export_modelica_component(
    spec: DuctSpec,
    conditions: PhysicsConditions | None = None,
) -> str:
    """Export a standards-compliant Modelica (.mo) fluid-thermal model calibrated to the FORGE duct."""
    cond = conditions or PhysicsConditions()
    phys = solve_duct_physics(spec, cond)
    spec_hash = sha256_hash(canonical_json(spec.to_canonical_dict()))[:10]

    q_ref = max(1e-5, phys.flow_rate_m3_s)
    # Quadratic turbulent hydraulic resistance coefficient K_turb = dP / Q^2 (Pa * s^2 / m^6)
    k_turb = phys.total_pressure_drop_pa / (q_ref ** 2)
    r_lam = 0.08 * phys.friction_pressure_drop_pa / q_ref

    return f"""within FORGE.ThermalFluid;

model FORGE_CoolingDuct_{spec_hash} "Calibrated 1D Thermo-Fluid Digital Twin (SHA-256: {spec_hash})"
  // Geometric & aerodynamic parameters synthesized by FORGE
  parameter Real inletWidth_mm = {spec.inlet_width:.3f} "Inlet width (mm)";
  parameter Real inletHeight_mm = {spec.inlet_height:.3f} "Inlet height (mm)";
  parameter Real outletWidth_mm = {spec.outlet_width:.3f} "Outlet width (mm)";
  parameter Real outletHeight_mm = {spec.outlet_height:.3f} "Outlet height (mm)";
  parameter Real length_mm = {spec.length:.3f} "Axial length (mm)";
  parameter Real hydraulicDiameter_m = {phys.hydraulic_diameter_mm / 1000.0:.5f} "Mean hydraulic diameter (m)";
  parameter Real flowUniformityIndex = {phys.flow_uniformity_index:.4f} "Exit velocity uniformity gamma";
  parameter Real R_laminar = {r_lam:.3f} "Laminar linear resistance (Pa.s/m3)";
  parameter Real K_turbulent = {k_turb:.3f} "Turbulent quadratic impedance (Pa.s2/m6)";
  parameter Real airDensity = {cond.air_density_kg_m3:.4f} "Air density (kg/m3)";
  parameter Real cp_air = 1005.0 "Specific heat capacity of air (J/(kg.K))";

  // System variables
  Real Q_flow_m3_s(start = {q_ref:.6f}) "Volumetric airflow rate (m3/s)";
  Real p_in_Pa(start = {cond.air_pressure_pa + phys.total_pressure_drop_pa:.2f}) "Inlet static pressure (Pa)";
  Real p_out_Pa(start = {cond.air_pressure_pa:.2f}) "Outlet static pressure (Pa)";
  Real delta_p_Pa "Total static pressure drop across duct (Pa)";
  Real Q_heat_W(start = {cond.heat_dissipation_watts:.2f}) "Downstream accelerator thermal load (W)";
  Real T_in_C(start = {cond.air_temp_c:.2f}) "Inlet air temperature (degC)";
  Real T_out_C "Exhaust air temperature (degC)";

equation
  delta_p_Pa = p_in_Pa - p_out_Pa;
  delta_p_Pa = R_laminar * Q_flow_m3_s + K_turbulent * Q_flow_m3_s * abs(Q_flow_m3_s);
  (airDensity * max(1e-5, Q_flow_m3_s) * cp_air) * (T_out_C - T_in_C) = Q_heat_W;

  annotation (
    Documentation(info="<html><p>Auto-generated by FORGE Inverse-Design Platform.</p></html>")
  );
end FORGE_CoolingDuct_{spec_hash};
"""

