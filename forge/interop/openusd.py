"""NVIDIA Omniverse / Pixar OpenUSD (.usda) 3D geometry and physics digital twin exporter."""
from __future__ import annotations
from typing import Dict, List, Tuple
from forge.core.geometry import Triangle, Vec3
from forge.core.hashes import canonical_json, sha256_hash
from forge.core.models import DuctSpec, PhysicsConditions
from forge.cad.dfm import analyze_dfm
from forge.cad.mesh import build_duct_mesh
from forge.physics.solver_1d import solve_duct_physics


MATERIAL_PBR_COLORS: Dict[str, Tuple[float, float, float, float, float]] = {
    # (R, G, B, metallic, roughness)
    "PC-CF": (0.14, 0.16, 0.18, 0.25, 0.35),
    "PA12-CF": (0.16, 0.17, 0.20, 0.20, 0.40),
    "PEEK": (0.76, 0.65, 0.48, 0.05, 0.30),
    "ASA": (0.22, 0.58, 0.85, 0.10, 0.35),
    "ABS": (0.25, 0.28, 0.32, 0.10, 0.40),
    "PETG": (0.20, 0.72, 0.92, 0.10, 0.25),
}


def export_openusd_stage(
    spec: DuctSpec,
    conditions: PhysicsConditions | None = None,
    triangles: List[Triangle] | None = None,
) -> str:
    """Export a Pixar OpenUSD ASCII (.usda) stage for NVIDIA Omniverse, Isaac Sim, and Blender.

    Embeds the watertight 3D mesh, PBR UsdPreviewSurface material, and custom `forge:physics:*`
    and `forge:dfm:*` digital twin telemetry attributes on the root Xform prim.
    """
    cond = conditions or PhysicsConditions()
    tris = triangles if triangles is not None else build_duct_mesh(spec)
    phys = solve_duct_physics(spec, cond)
    dfm = analyze_dfm(spec, tris)
    spec_hash = sha256_hash(canonical_json(spec.to_canonical_dict()))

    vert_map: Dict[Tuple[float, float, float], int] = {}
    verts: List[Vec3] = []
    face_indices: List[int] = []
    normals: List[Vec3] = []

    for tri in tris:
        n = tri.normal
        normals.extend([n, n, n])
        for v in (tri.a, tri.b, tri.c):
            key = (round(v.x, 4), round(v.y, 4), round(v.z, 4))
            if key not in vert_map:
                vert_map[key] = len(verts)
                verts.append(v)
            face_indices.append(vert_map[key])

    face_counts = ", ".join(["3"] * len(tris))
    face_idx_str = ", ".join(str(i) for i in face_indices)
    pts_str = ", ".join(f"({v.x:.4f}, {v.y:.4f}, {v.z:.4f})" for v in verts)
    norms_str = ", ".join(f"({n.x:.4f}, {n.y:.4f}, {n.z:.4f})" for n in normals)

    r, g, b, metallic, roughness = MATERIAL_PBR_COLORS.get(
        spec.material.value, (0.20, 0.72, 0.92, 0.15, 0.35)
    )

    return f"""#usda 1.0
(
    defaultPrim = "FORGE_DigitalTwin"
    metersPerUnit = 0.001
    upAxis = "Z"
    doc = "Generated by FORGE AI-Accelerated Physical Inverse-Design Platform"
)

def Xform "FORGE_DigitalTwin" (
    kind = "component"
)
{{
    custom string forge:geometry:sha256 = "{spec_hash}"
    custom string forge:material:name = "{spec.material.value}"
    custom double forge:physics:totalPressureDropPa = {phys.total_pressure_drop_pa}
    custom double forge:physics:flowUniformityIndex = {phys.flow_uniformity_index}
    custom double forge:physics:reynoldsNumber = {phys.reynolds_number}
    custom double forge:physics:acousticNoiseDba = {phys.acoustic_noise_dba}
    custom double forge:physics:maxWallDeflectionUm = {phys.max_wall_deflection_um}
    custom double forge:physics:fanOperatingCfm = {phys.fan_operating_cfm or cond.volumetric_flow_cfm}
    custom double forge:dfm:estimatedMassGrams = {dfm.estimated_mass_grams}
    custom bool forge:dfm:overhangCompliance = {str(dfm.overhang_compliance).lower()}

    def Mesh "CoolingDuctMesh" (
        prepend apiSchemas = ["MaterialBindingAPI"]
    )
    {{
        rel material:binding = </FORGE_DigitalTwin/Materials/DuctPBRMaterial>
        int[] faceVertexCounts = [{face_counts}]
        int[] faceVertexIndices = [{face_idx_str}]
        point3f[] points = [{pts_str}]
        normal3f[] normals = [{norms_str}] (
            interpolation = "faceVarying"
        )
        uniform token subdivisionScheme = "none"
    }}

    def Scope "Materials"
    {{
        def Material "DuctPBRMaterial"
        {{
            token outputs:surface.connect = </FORGE_DigitalTwin/Materials/DuctPBRMaterial/PBRShader.outputs:surface>

            def Shader "PBRShader"
            {{
                uniform token info:id = "UsdPreviewSurface"
                color3f inputs:diffuseColor = ({r:.3f}, {g:.3f}, {b:.3f})
                float inputs:metallic = {metallic:.3f}
                float inputs:roughness = {roughness:.3f}
                token outputs:surface
            }}
        }}
    }}
}}
"""

