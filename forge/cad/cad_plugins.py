"""Parametric CAD ecosystem code generators for Onshape (FeatureScript), FreeCAD (OpenCASCADE Python), and OpenSCAD."""
from __future__ import annotations
from forge.core.hashes import canonical_json, sha256_hash
from forge.core.models import DuctSpec
from forge.cad.mesh import build_duct_mesh


def export_onshape_featurescript(spec: DuctSpec) -> str:
    """Generate a self-contained Onshape FeatureScript studio module for native B-Rep CAD instantiation."""
    spec_hash = sha256_hash(canonical_json(spec.to_canonical_dict()))[:12]
    return f"""FeatureScript 2411;
import(path : "onshape/std/geometry.fs", version : "2411.0");

// Auto-generated by FORGE Generative Inverse-Design Platform
// Geometry SHA-256 Prefix: {spec_hash}
// Material: {spec.material.value}

annotation {{ "Feature Type Name" : "FORGE Cooling Duct ({spec_hash})" }}
export const forgeCoolingDuct = defineFeature(function(context is Context, id is Id, definition is map)
    precondition
    {{
        annotation {{ "Name" : "Inlet Width (mm)" }}
        isLength(definition.inletWidth, {{ (millimeter) : [10, {spec.inlet_width:.2f}, 500] }} as LengthBoundSpec);
        annotation {{ "Name" : "Inlet Height (mm)" }}
        isLength(definition.inletHeight, {{ (millimeter) : [10, {spec.inlet_height:.2f}, 500] }} as LengthBoundSpec);
        annotation {{ "Name" : "Outlet Width (mm)" }}
        isLength(definition.outletWidth, {{ (millimeter) : [10, {spec.outlet_width:.2f}, 500] }} as LengthBoundSpec);
        annotation {{ "Name" : "Outlet Height (mm)" }}
        isLength(definition.outletHeight, {{ (millimeter) : [10, {spec.outlet_height:.2f}, 500] }} as LengthBoundSpec);
        annotation {{ "Name" : "Length (mm)" }}
        isLength(definition.length, {{ (millimeter) : [15, {spec.length:.2f}, 1000] }} as LengthBoundSpec);
        annotation {{ "Name" : "Wall Thickness (mm)" }}
        isLength(definition.wall, {{ (millimeter) : [0.8, {spec.wall:.2f}, 20] }} as LengthBoundSpec);
    }}
    {{
        const inW = {spec.inlet_width:.3f} * millimeter;
        const inH = {spec.inlet_height:.3f} * millimeter;
        const outW = {spec.outlet_width:.3f} * millimeter;
        const outH = {spec.outlet_height:.3f} * millimeter;
        const len = {spec.length:.3f} * millimeter;
        const offX = {spec.offset_x:.3f} * millimeter;
        const offY = {spec.offset_y:.3f} * millimeter;
        const wallT = {spec.wall:.3f} * millimeter;

        var sketchInlet = newSketchOnPlane(context, id + "sketchInlet", {{
            "sketchPlane" : plane(vector(0, 0, 0) * millimeter, vector(0, 0, 1))
        }});
        skRectangle(sketchInlet, "inletRect", {{
            "firstCorner" : vector(-inW / 2, -inH / 2),
            "secondCorner" : vector(inW / 2, inH / 2)
        }});
        skSolve(sketchInlet);

        var sketchOutlet = newSketchOnPlane(context, id + "sketchOutlet", {{
            "sketchPlane" : plane(vector(offX, offY, len), vector(0, 0, 1))
        }});
        skRectangle(sketchOutlet, "outletRect", {{
            "firstCorner" : vector(-outW / 2, -outH / 2),
            "secondCorner" : vector(outW / 2, outH / 2)
        }});
        skSolve(sketchOutlet);

        opLoft(context, id + "outerLoft", {{
            "profileSubqueries" : [
                qSketchRegion(id + "sketchInlet"),
                qSketchRegion(id + "sketchOutlet")
            ],
            "bodyType" : ToolBodyType.SOLID
        }});

        opShell(context, id + "hollowDuct", {{
            "entities" : qCapEntity(id + "outerLoft", CapType.EITHER, true),
            "thickness" : -wallT
        }});
    }});
"""


def export_freecad_macro(spec: DuctSpec) -> str:
    """Generate a native FreeCAD / OpenCASCADE Python macro (.FCMacro) building parametric lofted B-Rep solids."""
    spec_hash = sha256_hash(canonical_json(spec.to_canonical_dict()))[:12]
    return f'''"""FORGE Parametric FreeCAD / OpenCASCADE Macro (SHA-256: {spec_hash})."""
import FreeCAD as App
import Part

doc = App.newDocument("FORGE_Duct_{spec_hash}")

INLET_W = {spec.inlet_width:.3f}
INLET_H = {spec.inlet_height:.3f}
OUTLET_W = {spec.outlet_width:.3f}
OUTLET_H = {spec.outlet_height:.3f}
LENGTH = {spec.length:.3f}
WALL = {spec.wall:.3f}
OFFSET_X = {spec.offset_x:.3f}
OFFSET_Y = {spec.offset_y:.3f}


def make_rect_wire(w: float, h: float, cx: float, cy: float, cz: float) -> Part.Wire:
    hw, hh = w / 2.0, h / 2.0
    pts = [
        App.Vector(cx - hw, cy - hh, cz),
        App.Vector(cx + hw, cy - hh, cz),
        App.Vector(cx + hw, cy + hh, cz),
        App.Vector(cx - hw, cy + hh, cz),
        App.Vector(cx - hw, cy - hh, cz),
    ]
    return Part.makePolygon(pts)


outer_in = make_rect_wire(INLET_W, INLET_H, 0.0, 0.0, 0.0)
outer_out = make_rect_wire(OUTLET_W, OUTLET_H, OFFSET_X, OFFSET_Y, LENGTH)
outer_solid = Part.makeLoft([outer_in, outer_out], True, False)

inner_in = make_rect_wire(INLET_W - 2.0 * WALL, INLET_H - 2.0 * WALL, 0.0, 0.0, 0.0)
inner_out = make_rect_wire(OUTLET_W - 2.0 * WALL, OUTLET_H - 2.0 * WALL, OFFSET_X, OFFSET_Y, LENGTH)
inner_cavity = Part.makeLoft([inner_in, inner_out], True, False)

duct_shape = outer_solid.cut(inner_cavity)
part_obj = doc.addObject("Part::Feature", "FORGE_Duct")
part_obj.Shape = duct_shape
doc.recompute()
'''


def export_openscad_script(spec: DuctSpec) -> str:
    """Generate a self-contained OpenSCAD (.scad) polyhedron script from the exact FORGE manifold mesh."""
    tris = build_duct_mesh(spec)
    vert_map = {}
    verts = []
    faces = []

    for tri in tris:
        f_idx = []
        for v in (tri.a, tri.b, tri.c):
            key = (round(v.x, 4), round(v.y, 4), round(v.z, 4))
            if key not in vert_map:
                vert_map[key] = len(verts)
                verts.append(key)
            f_idx.append(vert_map[key])
        faces.append(f_idx)

    pts_str = ",\n    ".join(f"[{x:.4f}, {y:.4f}, {z:.4f}]" for (x, y, z) in verts)
    faces_str = ",\n    ".join(f"[{i0}, {i1}, {i2}]" for (i0, i1, i2) in faces)

    return (
        f"// FORGE Parametric OpenSCAD Model ({spec.material.value})\n"
        f"inlet_width = {spec.inlet_width:.2f};\n"
        f"inlet_height = {spec.inlet_height:.2f};\n"
        f"outlet_width = {spec.outlet_width:.2f};\n"
        f"outlet_height = {spec.outlet_height:.2f};\n"
        f"duct_length = {spec.length:.2f};\n\n"
        "module forge_duct() {\n"
        "  polyhedron(\n"
        f"    points = [\n    {pts_str}\n    ],\n"
        f"    faces = [\n    {faces_str}\n    ],\n"
        "    convexity = 10\n"
        "  );\n"
        "}\n\n"
        "forge_duct();\n"
    )
